/**
 * The Knowledge Graph Conference blog archive, as data.
 *
 * Scraped once from the live WordPress at
 * `knowledgegraph.tech/wp-json/wp/v2/posts` and checked in, rather than fetched
 * at request time, because the site has to build and render with no network —
 * and because a marketing page that goes blank when someone else's CMS is down
 * is a worse page than a slightly stale one.
 *
 * `excerpt` is the excerpt WordPress itself publishes, not the article body.
 * These posts are substantially guest-authored, so their copyright is not
 * uniformly the conference's to relocate; republishing them in full here would
 * be a rights decision rather than an engineering one. Every post therefore
 * carries its author and a link to the canonical article, and the detail pages
 * declare that canonical URL to search engines so this site never competes with
 * the original for the same words.
 *
 * To refresh: re-run the REST query, regenerate this file, and re-download the
 * featured images into `public/kgc/blog/`. Full-text migration is a follow-up
 * that needs the owner's confirmation of rights plus a WordPress export.
 */

export type Post = {
  /** The live site's own slug, so `/blog/<slug>` mirrors `knowledgegraph.tech/blog/<slug>`. */
  slug: string;
  title: string;
  /** Plain `YYYY-MM-DD`. Publication day, not an instant — see `formatPostDate`. */
  date: string;
  author: string;
  /** The author's archive page on the live site, where WordPress gave us one. */
  authorUrl: string | null;
  categories: string[];
  tags: string[];
  excerpt: string;
  /**
   * `true` when WordPress published no excerpt and this is instead the opening
   * words of the body, shown as a quotation with the canonical link beside it.
   */
  excerptIsQuote: boolean;
  /** The canonical article on knowledgegraph.tech. */
  url: string;
  /**
   * The featured image, downloaded into `public/kgc/blog/` at scrape time.
   *
   * Local rather than hot-linked: `next/image` would need `knowledgegraph.tech`
   * in `images.remotePatterns`, and hot-linking would leave 70 cards dependent
   * on someone else's uptime for the thing that makes them look like cards.
   */
  image: string | null;
  imageWidth: number;
  imageHeight: number;
};

