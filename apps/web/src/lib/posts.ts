/**
 * Every category that actually has posts, most-used first.
 *
 * Derived rather than typed out so the filter row cannot drift from the data:
 * offering a filter that matches nothing is the specific failure this avoids.
 */
export const POST_CATEGORIES: { name: string; count: number }[] = (() => {
  const counts = new Map<string, number>();
  for (const post of POSTS) {
    for (const category of post.categories) {
      counts.set(category, (counts.get(category) ?? 0) + 1);
    }
  }
  return [...counts.entries()]
    .map(([name, count]) => ({ name, count }))
    .sort((a, b) => b.count - a.count || a.name.localeCompare(b.name));
})();

export function getPost(slug: string): Post | undefined {
  return POSTS.find((post) => post.slug === slug);
}

/**
 * `2025-09-08` → `8 September 2025`.
 *
 * `Date.UTC` + a UTC formatter, exactly as `formatDayHeading` in `site.ts` does
 * and for the same reason: these are plain publication dates, and
 * `new Date('2025-09-08')` formatted locally reads a day early west of
 * Greenwich — which would silently misdate half this archive.
 */
export function formatPostDate(date: string): string {
  const [y, m, d] = date.split('-').map(Number);
  return new Intl.DateTimeFormat('en-GB', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
    timeZone: 'UTC',
  }).format(new Date(Date.UTC(y, m - 1, d)));
}

/** The posts in a category, or all of them when `category` is not a real one. */
export function postsInCategory(category: string | null): Post[] {
  if (!category) return POSTS;
  return POSTS.filter((post) => post.categories.includes(category));
}
